    raise exception 'not_admin' using errcode = '42501';
  end if;
  if nullif(btrim(coalesce(p_path, '')), '') is null then
    return jsonb_build_object('ok', false, 'error', 'caminho_obrigatorio');
  end if;

  update public.reembolsos
     set comprovante_path = btrim(p_path)
   where id = p_reembolso_id and status in ('aprovado', 'pago');
  if not found then
    return jsonb_build_object('ok', false, 'error', 'reembolso_nao_encontrado');
  end if;
  return jsonb_build_object('ok', true);
end;
$anexo$;


-- Aprovar: é AQUI que o ingresso é cancelado e a vaga volta para a venda.
-- Não movimenta dinheiro: o pedido passa a esperar o pagamento, feito por fora.
create or replace function public.admin_reembolso_aprovar(p_reembolso_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $apr$
declare
  _uid   uuid := auth.uid();
  _r     record;
  _o     record;
  _sobram int;
  _tem_produto boolean;
  _lot   record;
  _modo  text;
  _cancelados int := 0;
begin
  if not public.has_role(_uid, 'admin'::app_role) then
    raise exception 'not_admin' using errcode = '42501';
  end if;

  select r.id, r.status, r.order_id, r.numero into _r
    from public.reembolsos r
   where r.id = p_reembolso_id
   for update;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'reembolso_nao_encontrado');
  end if;
  if _r.status <> 'solicitado' then
    return jsonb_build_object('ok', false, 'error', 'invalid_status', 'current_status', _r.status);
  end if;

  select o.id, o.status into _o from public.orders o where o.id = _r.order_id for update;

  -- Marca o pedido de reembolso PRIMEIRO: a trava dos ingressos olha o status
  -- 'solicitado', e o cancelamento logo abaixo não pode esbarrar nela.
  update public.reembolsos
     set status = 'aprovado', decidido_em = now(), decidido_por = _uid
   where id = p_reembolso_id;

  if _o.status = 'paid' then
    -- Ingressos do pedido que ficam de pé depois deste reembolso.
    select count(*) into _sobram
      from public.tickets t
     where t.order_id = _r.order_id
       and t.status in ('valid', 'used')
       and not exists (select 1 from public.reembolso_ingressos ri
                        where ri.reembolso_id = p_reembolso_id and ri.ticket_id = t.id);
    select exists (select 1 from public.order_product_items i where i.order_id = _r.order_id)
      into _tem_produto;

    if _sobram = 0 and not _tem_produto then
      -- O pedido inteiro foi devolvido: a porta de sempre faz a cascata
      -- (estoque, mesa, ingressos, cupom, auditoria) e o pedido vira 'refunded'.
      perform public.cancel_paid_order(_r.order_id, 'refunded',
                'Reembolso nº ' || _r.numero || ' aprovado pela casa');
      _modo := 'pedido_inteiro';
    else
      -- Sobrou ingresso: o pedido continua pago; só os devolvidos são cancelados.
      if exists (select 1 from public.reembolso_ingressos ri
                   join public.tickets t on t.id = ri.ticket_id
                  where ri.reembolso_id = p_reembolso_id and t.event_seat_id is not null) then
        raise exception 'mesa_parcial_nao_suportada' using errcode = '22023';
      end if;

      -- Marca os ingressos primeiro, devolve o estoque depois (padrão da casa:
      -- inverter reabre venda em dobro sob carga).
      for _lot in
        with cancelados as (
          update public.tickets t
             set status = 'cancelled'
           where t.status = 'valid'
             and t.id in (select ri.ticket_id from public.reembolso_ingressos ri
                           where ri.reembolso_id = p_reembolso_id)
          returning t.lot_id
        )
        select lot_id, count(*)::int as qty from cancelados group by lot_id
      loop
        _cancelados := _cancelados + _lot.qty;
        if _lot.lot_id is not null then
          update public.event_lots
             set sold_quantity = greatest(0, sold_quantity - _lot.qty)
           where id = _lot.lot_id;
        end if;
      end loop;

      insert into public.audit_logs (actor_id, action, target_type, target_id, metadata)
      values ('95628c4a-8040-44ed-83c5-d6a5b8793926', 'paid_order_partially_refunded', 'order', _r.order_id,
              jsonb_build_object('reembolso_id', p_reembolso_id, 'numero', _r.numero, 'ingressos_cancelados', _cancelados));
      _modo := 'parcial';
    end if;
  else
    -- O pedido já saiu de 'paid' por outro caminho (produtor cancelou,
    -- contestação). Não há o que cancelar; sobra só o pagamento a conferir.
    _modo := 'pedido_ja_encerrado';
  end if;

  update public.reembolsos set modo_cancelamento = _modo where id = p_reembolso_id;

  insert into public.audit_logs (actor_id, action, target_type, target_id, metadata)
  values (_uid, 'refund_approved', 'order', _r.order_id,
          jsonb_build_object('reembolso_id', p_reembolso_id, 'numero', _r.numero, 'modo', _modo));

  return jsonb_build_object('ok', true, 'status', 'aprovado', 'modo', _modo);
end;
$apr$;


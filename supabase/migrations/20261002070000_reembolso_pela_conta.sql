-- ── 6. A conta do repasse ───────────────────────────────────────────────────
-- Reembolso pedido, aprovado ou pago SAI do valor do produtor. Pedido ainda em
-- análise também sai: é o caso da Luana (01/10), que pediu repasse de um
-- dinheiro que estava voltando para a compradora. Recusado ou desistido, o
-- valor volta sozinho.
--
-- A mudança mora na fórmula única (`order_producer_value`), então o painel do
-- produtor, o pedido de repasse e o aviso de repasse passam a concordar sem
-- que nenhum deles precise saber de reembolso.
--
-- CREATE OR REPLACE, nunca DROP+CREATE (devolveria a permissão ao público).
-- Sem reembolso no pedido, o resultado é IDÊNTICO ao de antes.
create or replace function public.order_producer_value(o public.orders)
returns numeric
language sql
stable
security definer
set search_path to 'public'
as $function$
  SELECT public.order_producer_value_bruto(o)
       - COALESCE((SELECT SUM(r.valor_ingressos)
                     FROM public.reembolsos r
                    WHERE r.order_id = o.id
                      AND r.status IN ('solicitado', 'aprovado', 'pago')), 0);
$function$;

comment on function public.order_producer_value(public.orders) is
  'Valor do ingresso de um pedido para o PRODUTOR (sem taxa de conveniência e sem juro de parcela), já descontado o que foi ou está sendo reembolsado. Fórmula única: usada por request_payout (via base_de_repasse) e pelo painel (producer_order_values).';

-- ── 7. O aviso para a casa ──────────────────────────────────────────────────
-- Mesmo motor do aviso de repasse (23/09): gatilho → pg_net → edge → WhatsApp
-- e push da gestão, com registro do que saiu e repesca do que não saiu.
create table if not exists public.reembolso_avisos (
  id           uuid primary key default gen_random_uuid(),
  reembolso_id uuid not null references public.reembolsos(id) on delete cascade,
  canal        text not null check (canal in ('whatsapp', 'gestao')),
  -- número mascarado ou nome do destino. NUNCA o número inteiro (LGPD).
  destino      text,
  -- nulo = ainda não saiu. É este campo que a repesca olha.
  enviado_em   timestamptz,
  tentativas   integer not null default 0,
  ultimo_erro  text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (reembolso_id, canal)
);

comment on table public.reembolso_avisos is
  'Prova de que o aviso de pedido de reembolso saiu. Uma linha por pedido e canal; enviado_em nulo = a repesca ainda vai tentar.';


-- REGRA DE OURO, igual à do repasse: falhar ao avisar NUNCA pode derrubar o
-- pedido de reembolso. O comprador clicou, o pedido tem que nascer.
create or replace function public.avisar_reembolso_solicitado()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  _segredo text;
begin
  if new.status is distinct from 'solicitado' then
    return new;
  end if;

  select decrypted_secret into _segredo
    from vault.decrypted_secrets where name = 'CRON_SECRET' limit 1;

  if _segredo is null then
    raise warning '[AVISO-REEMBOLSO] CRON_SECRET nao encontrado no Vault; aviso do reembolso % nao foi disparado', new.id;
    return new;
  end if;

  perform net.http_post(
    url     := 'https://nsrromaqysgoxqvqagdm.supabase.co/functions/v1/aviso-reembolso',
    headers := jsonb_build_object(
                 'Content-Type', 'application/json',
                 'X-Cron-Secret', _segredo
               ),
    body    := jsonb_build_object('reembolso_id', new.id, 'origem', 'gatilho'),
    timeout_milliseconds := 25000
  );

  return new;
exception when others then
  raise warning '[AVISO-REEMBOLSO] gatilho falhou para o reembolso %: %', new.id, sqlerrm;
  return new;
end;
$fn$;

comment on function public.avisar_reembolso_solicitado() is
  'Chama a edge aviso-reembolso quando nasce um pedido de reembolso. Nunca derruba a operação que o criou.';

drop trigger if exists trg_reembolsos_aviso on public.reembolsos;
create trigger trg_reembolsos_aviso
  after insert on public.reembolsos
  for each row execute function public.avisar_reembolso_solicitado();


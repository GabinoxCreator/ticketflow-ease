-- ============================================================================
-- OS-103 · Cancelar o ingresso e pedir reembolso pela conta do comprador
--
-- Por que (01/10/2026): o comprador só conseguia pedir reembolso por e-mail ou
-- WhatsApp. Alguém da casa conferia na mão, o João pagava o PIX e depois o
-- pedido era cancelado no sistema. O Decreto 7.962 (art. 5º) pede que a
-- desistência seja feita pela mesma ferramenta da compra, com confirmação na
-- hora. E o caso da Luana (01/10) mostrou o risco de dinheiro: o pedido de
-- repasse dela incluía R$ 100 de um ingresso que estava sendo reembolsado.
--
-- Decisões do Gabriel (caixinha, 02/10/2026):
--   1. A CASA APROVA ANTES. O clique do comprador gera um pedido; o ingresso
--      fica BLOQUEADO (não entra, não transfere) até alguém aprovar. Só a
--      aprovação cancela o ingresso e devolve a vaga.
--   2. PIX pela fila; compra no cartão volta no cartão. NADA É PAGO PELO
--      SISTEMA: a fila mostra o que pagar, a casa paga e dá baixa.
--   3. INGRESSO POR INGRESSO. O comprador escolhe quais devolver.
--   4. A taxa dentro dos 7 dias espera o advogado: a regra mora em UMA função
--      (`reembolso_regra`) e muda em uma linha.
--
-- O que este arquivo faz, na ordem:
--   1. tabelas `reembolsos` e `reembolso_ingressos` (o pedido e seus ingressos)
--   2. a regra (prazo e taxa) e o valor de cada ingresso, cada um em um lugar só
--   3. as portas do comprador: simular, pedir, desistir
--   4. a trava: ingresso com reembolso em análise não entra nem é transferido
--   5. as portas da casa: listar, aprovar, recusar, dar baixa
--   6. a conta do repasse: reembolso (pendente ou feito) sai do valor do produtor
--   7. o aviso para a casa (mesmo motor do aviso de repasse)
--
-- PEDIDO NUNCA É APAGADO. Aprovar reaproveita `cancel_paid_order` quando o
-- pedido fica sem ingresso válido; quando sobra ingresso, o pedido continua
-- `paid` e só os ingressos devolvidos viram `cancelled`.
-- ============================================================================

-- ── 1. O pedido de reembolso ────────────────────────────────────────────────
create table if not exists public.reembolsos (
  id                uuid primary key default gen_random_uuid(),
  -- O protocolo que o comprador vê e a casa cita no WhatsApp.
  numero            bigint generated by default as identity (start with 1001) unique,
  order_id          uuid not null references public.orders(id),
  event_id          uuid not null references public.events(id),
  -- Quem pediu. Sem FK de propósito: a conta pode ser excluída (LGPD) e o
  -- registro do dinheiro devolvido tem que ficar.
  user_id           uuid not null,
  -- solicitado → a casa ainda não olhou; os ingressos estão bloqueados
  -- aprovado   → ingressos cancelados, vaga devolvida; falta pagar
  -- pago       → a casa deu baixa
  -- recusado   → a casa negou; os ingressos voltam a valer
  -- desistido  → o comprador voltou atrás antes da resposta
  status            text not null default 'solicitado'
                    check (status in ('solicitado','aprovado','pago','recusado','desistido')),
  -- Valores CONGELADOS no momento do pedido: é a regra daquele dia que vale,
  -- mesmo que a regra mude depois.
  valor_ingressos   numeric(12,2) not null check (valor_ingressos >= 0),
  valor_taxa        numeric(12,2) not null default 0 check (valor_taxa >= 0),
  devolve_taxa      boolean not null default false,
  valor_a_devolver  numeric(12,2) not null check (valor_a_devolver >= 0),
  -- O que a regra respondeu: janela, versão da Política aceita, prazos.
  regra             jsonb not null default '{}'::jsonb,
  -- 'pix' = a casa paga na chave informada · 'cartao' = estorno no cartão
  forma             text not null check (forma in ('pix','cartao')),
  chave_pix         text,
  tipo_chave_pix    text check (tipo_chave_pix is null or tipo_chave_pix in ('cpf','cnpj','email','telefone','aleatoria')),
  motivo            text,
  solicitado_em     timestamptz not null default now(),
  decidido_em       timestamptz,
  decidido_por      uuid,
  motivo_recusa     text,
  -- Como o cancelamento foi feito na aprovação: 'pedido_inteiro' | 'parcial' | 'pedido_ja_encerrado'
  modo_cancelamento text,
  pago_em           timestamptz,
  pago_por          uuid,
  observacao_pagamento text,
  comprovante_path  text,
  desistido_em      timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint reembolsos_pix_tem_chave check (forma <> 'pix' or chave_pix is not null)
);

comment on table public.reembolsos is
  'Pedido de reembolso feito pelo comprador em Meus Ingressos. A casa aprova, paga por fora e dá baixa. O sistema nunca movimenta dinheiro.';

-- Um pedido em análise por compra, de cada vez (mesma ideia do
-- `uniq_payout_requested_per_event`): evita clique duplo e fila duplicada.
create unique index if not exists uq_reembolso_solicitado_por_pedido
  on public.reembolsos (order_id) where status = 'solicitado';
create index if not exists idx_reembolsos_order  on public.reembolsos (order_id);
create index if not exists idx_reembolsos_user   on public.reembolsos (user_id);
create index if not exists idx_reembolsos_status on public.reembolsos (status, solicitado_em);

create table if not exists public.reembolso_ingressos (
  reembolso_id   uuid not null references public.reembolsos(id) on delete cascade,
  ticket_id      uuid not null references public.tickets(id),
  valor_ingresso numeric(12,2) not null default 0,
  valor_taxa     numeric(12,2) not null default 0,
  primary key (reembolso_id, ticket_id)
);

comment on table public.reembolso_ingressos is
  'Quais ingressos entram em cada pedido de reembolso, com o valor de cada um congelado.';

create index if not exists idx_reembolso_ingressos_ticket on public.reembolso_ingressos (ticket_id);

alter table public.reembolsos enable row level security;
alter table public.reembolso_ingressos enable row level security;

-- O comprador vê os próprios pedidos; quem administra vê todos. Ninguém
-- escreve pela chave pública: tudo passa pelas funções abaixo.
drop policy if exists "comprador ve seus reembolsos" on public.reembolsos;
create policy "comprador ve seus reembolsos"
  on public.reembolsos for select
  using (user_id = auth.uid() or public.has_role(auth.uid(), 'admin'::app_role));

drop policy if exists "comprador ve os ingressos dos seus reembolsos" on public.reembolso_ingressos;
create policy "comprador ve os ingressos dos seus reembolsos"
  on public.reembolso_ingressos for select
  using (exists (
    select 1 from public.reembolsos r
     where r.id = reembolso_id
       and (r.user_id = auth.uid() or public.has_role(auth.uid(), 'admin'::app_role))
  ));

revoke all on public.reembolsos from anon, authenticated;
revoke all on public.reembolso_ingressos from anon, authenticated;
grant select on public.reembolsos to authenticated;
grant select on public.reembolso_ingressos to authenticated;

drop trigger if exists update_reembolsos_updated_at on public.reembolsos;
create trigger update_reembolsos_updated_at
  before update on public.reembolsos
  for each row execute function public.update_updated_at_column();

-- ── 2a. A REGRA, em um lugar só ─────────────────────────────────────────────
-- Espelha as seções 2, 3 e 7 da Política de Reembolso (e o `RESUMO_REEMBOLSO`
-- do site). Mudou a Política, muda AQUI, e em nenhum outro lugar: a tela do
-- comprador e a fila da casa só mostram o que esta função responde.
--
--   · arrependimento: até 7 dias corridos da compra, faltando mais de 7 dias
--     para o evento;
--   · fora disso: até 48 horas antes do início do evento;
--   · taxa de serviço: NÃO volta na desistência do comprador (regra de 30/09).
--     Exceção: quem comprou aceitando o texto ANTIGO da Política (versão
--     anterior a 2026-09-30), que prometia "integral, incluindo taxas" no
--     arrependimento. Para essas compras a taxa volta dentro dos 7 dias.
--
-- ⏳ ITEM 4 DA OS-103 (espera o advogado): se a resposta for "a taxa volta nos
-- 7 dias para todo mundo", a mudança é a linha marcada com [TAXA] abaixo.
create or replace function public.reembolso_regra(_order_id uuid, _agora timestamptz default now())
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $regra$
declare
  _o       record;
  _e       record;
  _forma   text;
  _inicio  timestamptz;
  _limite  timestamptz;
  _fim_arrependimento timestamptz;
  _janela  text;
  _versao  text;
  _texto_antigo boolean;
  _devolve_taxa boolean;
begin
  select o.id, o.status, o.sale_origin, o.payment_method, o.total_amount, o.created_at, o.event_id, o.user_id
    into _o
    from public.orders o
   where o.id = _order_id;
  if not found then
    return jsonb_build_object('permitido', false, 'motivo', 'pedido_nao_encontrado');
  end if;

  if _o.status <> 'paid' then
    return jsonb_build_object('permitido', false, 'motivo', 'pedido_nao_esta_pago');
  end if;

  -- Só o que a FestPag recebeu: venda manual, cortesia e maquininha da portaria
  -- foram pagas direto ao produtor (mesma fronteira da base de repasse).
  if coalesce(_o.sale_origin, 'online') <> 'online' then
    return jsonb_build_object('permitido', false, 'motivo', 'compra_fora_do_site');
  end if;

  _forma := case
    when lower(coalesce(_o.payment_method, '')) like 'pix%'  then 'pix'
    when lower(coalesce(_o.payment_method, '')) like 'card%' then 'cartao'
  end;
  if _forma is null then
    return jsonb_build_object('permitido', false, 'motivo', 'forma_de_pagamento_nao_suportada');
  end if;

  if coalesce(_o.total_amount, 0) <= 0 then
    return jsonb_build_object('permitido', false, 'motivo', 'sem_valor_pago');
  end if;

  -- Pedido com produto da loja (camiseta, combo) fica fora desta primeira
  -- versão: o produto tem retirada e estoque próprios. Vai pelo suporte.
  if exists (select 1 from public.order_product_items i where i.order_id = _order_id) then
    return jsonb_build_object('permitido', false, 'motivo', 'pedido_com_produto');
  end if;

  select e.date, e.time into _e from public.events e where e.id = _o.event_id;
  if not found or _e.date is null then
    return jsonb_build_object('permitido', false, 'motivo', 'evento_nao_encontrado');
  end if;

  -- Data e hora do evento são de Brasília (a coluna é `date` + `time`, sem fuso).
  _inicio := (_e.date + coalesce(_e.time, time '00:00')) at time zone 'America/Sao_Paulo';
  _limite := _inicio - interval '48 hours';

  -- 7 dias corridos em dias de calendário de Brasília, até o fim do 7º dia. O
  -- pedido nasce minutos antes da confirmação do pagamento; contar por dia
  -- inteiro nunca tira prazo do comprador.
  _fim_arrependimento :=
    (((_o.created_at at time zone 'America/Sao_Paulo')::date + 8)::timestamp) at time zone 'America/Sao_Paulo';

  if _agora < _fim_arrependimento and (_inicio - _agora) > interval '7 days' then
    _janela := 'arrependimento';
  elsif _agora <= _limite then
    _janela := 'ate_48h';
  else
    return jsonb_build_object(
      'permitido', false, 'motivo', 'fora_do_prazo',
      'forma', _forma, 'inicio_evento', _inicio, 'limite', _limite);
  end if;

  -- A regra que vale é a do dia da compra: a versão da Política que o
  -- comprador aceitou no pagamento.
  --
  -- ⚠️ O aceite é gravado quando a pessoa escolhe como pagar, ANTES de o pedido
  -- existir: em produção `aceites_legais.pedido_id` está sempre vazio (medido
  -- em 02/10/2026, 90 aceites de checkout, nenhum com pedido). Por isso a
  -- procura é pelo aceite da mesma pessoa mais próximo ANTES da compra. Se um
  -- dia o pedido passar a ser gravado, ele ganha.
  select a.versao into _versao
    from public.aceites_legais a
   where a.documento = 'reembolso'
     and (a.pedido_id = _order_id
          or (a.usuario_id = _o.user_id
              and a.aceito_em <= _o.created_at + interval '30 minutes'
              and a.aceito_em >= _o.created_at - interval '24 hours'))
   order by (a.pedido_id = _order_id) desc nulls last, a.aceito_em desc
   limit 1;
  -- Compra sem aceite gravado (anterior a 22/09, ou o registro falhou): vale o
  -- texto que estava no ar naquele dia. O novo entrou em 01/10/2026 às 12h25.
  if _versao is null then
    _versao := case when _o.created_at < timestamptz '2026-10-01 12:25:00-03'
                    then '2026-05-14' else '2026-09-30' end;
  end if;
  _texto_antigo := _versao < '2026-09-30';

  -- [TAXA] Hoje: a taxa só volta para quem aceitou o texto antigo, e só no
  -- arrependimento. Para devolver a taxa nos 7 dias a todos, trocar por:
  --   _devolve_taxa := (_janela = 'arrependimento');
  _devolve_taxa := (_janela = 'arrependimento' and _texto_antigo);

  return jsonb_build_object(
    'permitido', true,
    'janela', _janela,
    'devolve_taxa', _devolve_taxa,
    'versao_aceita', _versao,
    'forma', _forma,
    'inicio_evento', _inicio,
    'limite', _limite);
end;
$regra$;

comment on function public.reembolso_regra(uuid, timestamptz) is
  'A regra de reembolso, em um lugar só: prazo, janela e se a taxa volta. Espelha a Política de Reembolso. Mudou lá, muda aqui.';

-- ── 2b. O valor de cada ingresso ────────────────────────────────────────────
-- O valor do pedido para o produtor, ANTES de qualquer reembolso. É a fórmula
-- que estava em `order_producer_value` até hoje, copiada da produção sem mudar
-- uma vírgula. A função de sempre passa a descontar os reembolsos (seção 6).
create or replace function public.order_producer_value_bruto(o public.orders)
returns numeric
language sql
stable
security definer
set search_path to 'public'
as $function$
  SELECT COALESCE(
    (SELECT SUM(f.unit_face * f.quantity) FROM public.order_line_face f WHERE f.order_id = o.id)
      - COALESCE(o.discount_amount, 0),
    COALESCE(o.total_amount, 0) - COALESCE(o.service_fee_amount, 0)
  );
$function$;

comment on function public.order_producer_value_bruto(public.orders) is
  'Valor dos ingressos de um pedido (sem taxa e sem juro), antes de descontar reembolso. Uso interno: order_producer_value e o rateio do reembolso.';

-- Quanto vale cada ingresso de um pedido: o valor dos ingressos (já com o
-- desconto do cupom) e a taxa de serviço, repartidos pelo preço de face de
-- cada um. Conta em centavos e distribui a sobra, para a soma de todos os
-- ingressos bater EXATAMENTE com o pedido: devolver os 3 ingressos de um
-- pedido de R$ 100,00 dá R$ 100,00, nunca R$ 99,99.
create or replace function public.reembolso_valores(_order_id uuid)
returns table (ticket_id uuid, valor_ingresso numeric, valor_taxa numeric)
language sql
stable
security definer
set search_path = public
as $valores$
  with pedido as (
    select o.id,
           round(greatest(0, public.order_producer_value_bruto(o)) * 100)::bigint as ingressos_cent,
           -- A taxa que o COMPRADOR pagou. Quando o produtor absorve a taxa, o
           -- comprador não pagou nada além do ingresso e não há taxa a discutir.
           round(greatest(0, least(coalesce(o.service_fee_amount, 0),
                                   coalesce(o.total_amount, 0) - public.order_producer_value_bruto(o))) * 100)::bigint as taxa_cent
      from public.orders o
     where o.id = _order_id
  ),
  t as (
    select tk.id,
           coalesce(
             (select max(f.unit_face) from public.order_line_face f
               where f.order_id = tk.order_id and f.lot_id = tk.lot_id),
             l.price,
             0)::numeric as peso
      from public.tickets tk
      left join public.event_lots l on l.id = tk.lot_id
     where tk.order_id = _order_id
       and tk.status <> 'pending'
  ),
  s as (select coalesce(sum(peso), 0) as soma, count(*) as n from t),
  p as (
    -- Sem preço de face conhecido (mesa, pedido antigo): reparte por igual.
    select t.id,
           case when s.soma > 0 then t.peso / s.soma else 1.0 / nullif(s.n, 0) end as w
      from t, s
  ),
  c as (
    select p.id,
           floor(pedido.ingressos_cent * p.w)                                as ing_base,
           pedido.ingressos_cent * p.w - floor(pedido.ingressos_cent * p.w)  as ing_resto,
           floor(pedido.taxa_cent * p.w)                                     as taxa_base,
           pedido.taxa_cent * p.w - floor(pedido.taxa_cent * p.w)            as taxa_resto,
           pedido.ingressos_cent, pedido.taxa_cent
      from p, pedido
  ),
  d as (
    select c.*,
           row_number() over (order by c.ing_resto desc, c.id)  as ing_ordem,
           row_number() over (order by c.taxa_resto desc, c.id) as taxa_ordem,
           c.ingressos_cent - sum(c.ing_base) over ()           as ing_sobra,
           c.taxa_cent - sum(c.taxa_base) over ()               as taxa_sobra
      from c
  )
  select d.id,
         ((d.ing_base  + case when d.ing_ordem  <= d.ing_sobra  then 1 else 0 end) / 100.0)::numeric(12,2),
         ((d.taxa_base + case when d.taxa_ordem <= d.taxa_sobra then 1 else 0 end) / 100.0)::numeric(12,2)
    from d;
$valores$;

comment on function public.reembolso_valores(uuid) is
  'Valor de cada ingresso de um pedido (ingresso e taxa), em rateio que fecha no centavo. Fonte única do valor a devolver.';

-- ── 3. As portas do comprador ───────────────────────────────────────────────
-- Por que um ingresso não pode entrar no pedido. Nulo = pode.
create or replace function public.reembolso_motivo_do_ingresso(_ticket_id uuid, _dono uuid)
returns text
language sql
stable
security definer
set search_path = public
as $motivo$
  select case
    when t.status = 'used' or t.validated_at is not null then 'ingresso_ja_utilizado'
    when t.status = 'cancelled' then 'ingresso_ja_cancelado'
    when t.status <> 'valid' then 'ingresso_indisponivel'
    when t.user_id is distinct from _dono then 'ingresso_transferido'
    when t.abada_redeemed_at is not null then 'abada_ja_retirado'
    when exists (select 1 from public.ticket_transfers tr
                  where tr.ticket_id = t.id and tr.status = 'pendente' and tr.expires_at > now())
      then 'transferencia_em_andamento'
    when exists (select 1 from public.reembolso_ingressos ri
                   join public.reembolsos r on r.id = ri.reembolso_id
                  where ri.ticket_id = t.id and r.status = 'solicitado')
      then 'reembolso_em_analise'
  end
  from public.tickets t
  where t.id = _ticket_id;
$motivo$;

-- O que a tela mostra ANTES de o comprador confirmar: se pode, por que não
-- pode, quais ingressos entram e quanto volta. Não grava nada.
create or replace function public.reembolso_simular(_order_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $sim$
declare
  _uid   uuid := auth.uid();
  _dono  uuid;
  _regra jsonb;
  _mesa  boolean;
  _ingressos jsonb;
  _aberto jsonb;
begin
  if _uid is null then
    return jsonb_build_object('permitido', false, 'motivo', 'nao_autenticado');
  end if;

  select o.user_id into _dono from public.orders o where o.id = _order_id;
  if not found or _dono is distinct from _uid then
    return jsonb_build_object('permitido', false, 'motivo', 'pedido_nao_e_seu');
  end if;

  _regra := public.reembolso_regra(_order_id);

  select exists (select 1 from public.tickets t where t.order_id = _order_id and t.event_seat_id is not null)
    into _mesa;

  select coalesce(jsonb_agg(jsonb_build_object(
           'ticket_id', t.id,
           'codigo', upper(left(t.ticket_code, 8)),
           'titular', t.holder_name,
           'nome', coalesce(l.name, s.label, 'Ingresso'),
           'motivo', public.reembolso_motivo_do_ingresso(t.id, _dono),
           'valor_ingresso', v.valor_ingresso,
           'valor_taxa', v.valor_taxa
         ) order by coalesce(s.label, t.ticket_code)), '[]'::jsonb)
    into _ingressos
    from public.tickets t
    join public.reembolso_valores(_order_id) v on v.ticket_id = t.id
    left join public.event_lots l on l.id = t.lot_id
    left join public.event_seats s on s.id = t.event_seat_id
   where t.order_id = _order_id;

  select jsonb_build_object('id', r.id, 'numero', r.numero, 'solicitado_em', r.solicitado_em)
    into _aberto
    from public.reembolsos r
   where r.order_id = _order_id and r.status = 'solicitado'
   limit 1;

  -- Mesa é vendida inteira e volta inteira. Com algum lugar já usado, não há
  -- como devolver a mesa.
  if (_regra->>'permitido')::boolean and _mesa and exists (
       select 1 from public.tickets t
        where t.order_id = _order_id and t.status <> 'pending'
          and public.reembolso_motivo_do_ingresso(t.id, _dono) is not null) then
    _regra := jsonb_build_object('permitido', false, 'motivo',
                case when _aberto is not null then 'reembolso_em_analise' else 'mesa_indisponivel' end)
              || jsonb_build_object('forma', _regra->'forma', 'limite', _regra->'limite');
  end if;

  return _regra || jsonb_build_object(
    'mesa', _mesa,
    'ingressos', _ingressos,
    'pedido_aberto', _aberto);
end;
$sim$;

comment on function public.reembolso_simular(uuid) is
  'O que a tela de Meus Ingressos mostra antes do pedido: se pode, o motivo quando não pode, os ingressos e os valores. Não grava nada.';

-- O pedido. Devolve {ok:false, error:<código>} em vez de estourar: a tela
-- traduz o código para uma frase, e nenhum erro de regra vira "erro interno".
create or replace function public.reembolso_solicitar(
  _order_id       uuid,
  _ticket_ids     uuid[],
  _chave_pix      text default null,
  _tipo_chave_pix text default null,
  _motivo         text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $sol$
declare
  _uid    uuid := auth.uid();
  _o      record;
  _regra  jsonb;
  _ids    uuid[];
  _n      int;
  _mesa   boolean;
  _forma  text;
  _chave  text;
  _tipo   text;
  _motivo_limpo text;
  _devolve_taxa boolean;
  _v_ing  numeric(12,2);
  _v_taxa numeric(12,2);
  _total  numeric(12,2);
  _id     uuid;
  _numero bigint;
begin
  if _uid is null then
    return jsonb_build_object('ok', false, 'error', 'nao_autenticado');
  end if;

  -- A trava do pedido põe em fila dois cliques simultâneos na mesma compra.
  select o.id, o.user_id, o.event_id into _o
    from public.orders o
   where o.id = _order_id
   for update;
  if not found or _o.user_id is distinct from _uid then
    return jsonb_build_object('ok', false, 'error', 'pedido_nao_e_seu');
  end if;

  _regra := public.reembolso_regra(_order_id);
  if not (_regra->>'permitido')::boolean then
    return jsonb_build_object('ok', false, 'error', _regra->>'motivo', 'limite', _regra->'limite');
  end if;
  _forma := _regra->>'forma';
  _devolve_taxa := (_regra->>'devolve_taxa')::boolean;

  select array_agg(distinct x) into _ids from unnest(coalesce(_ticket_ids, '{}'::uuid[])) as x where x is not null;
  if _ids is null or array_length(_ids, 1) is null then
    return jsonb_build_object('ok', false, 'error', 'nenhum_ingresso_escolhido');
  end if;

  if exists (select 1 from public.reembolsos r where r.order_id = _order_id and r.status = 'solicitado') then
    return jsonb_build_object('ok', false, 'error', 'reembolso_em_analise');
  end if;

  -- Pedir e desistir em sequência dispara aviso para a casa a cada vez.
  if (select count(*) from public.reembolsos r where r.order_id = _order_id) >= 5 then
    return jsonb_build_object('ok', false, 'error', 'limite_de_pedidos');
  end if;

  -- Trava os ingressos escolhidos: nenhum check-in passa no meio deste pedido.
  select count(*) into _n
    from (select t.id from public.tickets t
           where t.id = any(_ids) and t.order_id = _order_id
           for update) travados;
  if _n <> array_length(_ids, 1) then
    return jsonb_build_object('ok', false, 'error', 'ingresso_invalido');
  end if;

  if exists (select 1 from unnest(_ids) as x
              where public.reembolso_motivo_do_ingresso(x, _uid) is not null) then
    return jsonb_build_object('ok', false, 'error', 'ingresso_indisponivel',
      'detalhe', (select jsonb_agg(jsonb_build_object('ticket_id', x, 'motivo', public.reembolso_motivo_do_ingresso(x, _uid)))
                    from unnest(_ids) as x
                   where public.reembolso_motivo_do_ingresso(x, _uid) is not null));
  end if;

  -- Mesa volta inteira: todos os lugares do pedido, juntos.
  select exists (select 1 from public.tickets t where t.order_id = _order_id and t.event_seat_id is not null)
    into _mesa;
  if _mesa and exists (select 1 from public.tickets t
                        where t.order_id = _order_id and t.status <> 'pending' and not (t.id = any(_ids))) then
    return jsonb_build_object('ok', false, 'error', 'mesa_inteira');
  end if;

  if _forma = 'pix' then
    _chave := nullif(btrim(coalesce(_chave_pix, '')), '');
    _tipo  := nullif(lower(btrim(coalesce(_tipo_chave_pix, ''))), '');
    if _chave is null or length(_chave) < 5 or length(_chave) > 140 then
      return jsonb_build_object('ok', false, 'error', 'chave_pix_invalida');
    end if;
    if _tipo is null or _tipo not in ('cpf','cnpj','email','telefone','aleatoria') then
      return jsonb_build_object('ok', false, 'error', 'tipo_de_chave_invalido');
    end if;
  end if;

  _motivo_limpo := nullif(left(btrim(coalesce(_motivo, '')), 500), '');

  select coalesce(sum(v.valor_ingresso), 0), coalesce(sum(v.valor_taxa), 0)
    into _v_ing, _v_taxa
    from public.reembolso_valores(_order_id) v
   where v.ticket_id = any(_ids);

  _total := _v_ing + case when _devolve_taxa then _v_taxa else 0 end;
  if _total <= 0 then
    return jsonb_build_object('ok', false, 'error', 'sem_valor_pago');
  end if;

  insert into public.reembolsos
    (order_id, event_id, user_id, valor_ingressos, valor_taxa, devolve_taxa, valor_a_devolver,
     regra, forma, chave_pix, tipo_chave_pix, motivo)
  values
    (_order_id, _o.event_id, _uid, _v_ing, _v_taxa, _devolve_taxa, _total,
     _regra, _forma, _chave, _tipo, _motivo_limpo)
  returning id, numero into _id, _numero;

  insert into public.reembolso_ingressos (reembolso_id, ticket_id, valor_ingresso, valor_taxa)
  select _id, v.ticket_id, v.valor_ingresso, v.valor_taxa
    from public.reembolso_valores(_order_id) v
   where v.ticket_id = any(_ids);

  insert into public.audit_logs (actor_id, action, target_type, target_id, metadata)
  values (_uid, 'refund_requested', 'order', _order_id,
          jsonb_build_object('reembolso_id', _id, 'numero', _numero, 'ingressos', array_length(_ids, 1),
                             'valor_a_devolver', _total, 'janela', _regra->>'janela', 'forma', _forma));

  return jsonb_build_object(
    'ok', true, 'reembolso_id', _id, 'numero', _numero,
    'valor_a_devolver', _total, 'valor_ingressos', _v_ing, 'valor_taxa', _v_taxa,
    'devolve_taxa', _devolve_taxa, 'forma', _forma);
end;
